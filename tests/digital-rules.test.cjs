const { test, after } = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const { initializeTestEnvironment, assertFails, assertSucceeds } = require('@firebase/rules-unit-testing');
const { doc, setDoc, updateDoc, getDoc, collection, query, where, getDocs, serverTimestamp } = require('firebase/firestore');
if (!process.env.FIRESTORE_EMULATOR_HOST) throw new Error('Firestore emulator required');
const [host, port] = process.env.FIRESTORE_EMULATOR_HOST.split(':');
const setup = initializeTestEnvironment({ projectId: 'demo-book-warehouse-digital', firestore: { host, port: Number(port), rules: fs.readFileSync('firestore.rules', 'utf8') } });
after(async () => (await setup).cleanup());
test('digital draft privacy, active roles, immutable file identity and publication validation', async () => {
  const env = await setup; await env.clearFirestore();
  await env.withSecurityRulesDisabled(async ctx => {
    await setDoc(doc(ctx.firestore(), 'adminGrants', 'admin'), { role: 'superuser', status: 'active' });
    await setDoc(doc(ctx.firestore(), 'adminGrants', 'inactive'), { role: 'admin', status: 'inactive' });
    await setDoc(doc(ctx.firestore(), 'adminGrants', 'wrong-role'), { role: 'operator', status: 'active' });
  });
  const admin = env.authenticatedContext('admin').firestore(), reader = env.authenticatedContext('reader').firestore();
  const guest = env.unauthenticatedContext().firestore(), inactive = env.authenticatedContext('inactive').firestore();
  const input = { title: 'Fictional test PDF', author: '', language: 'bn', description: '', size: 20, sha256: 'a'.repeat(64), folderId: 'folder', fileId: 'file', ownerUid: 'admin', status: 'uploading', readerUrl: '', createdAt: serverTimestamp(), updatedAt: serverTimestamp() };
  for (const db of [reader, guest, inactive, env.authenticatedContext('wrong-role').firestore()]) await assertFails(setDoc(doc(db, 'digitalBooks', 'no'), input));
  const ref = doc(admin, 'digitalBooks', 'one'); await assertSucceeds(setDoc(ref, input));
  await assertFails(setDoc(doc(admin, 'digitalBooks', 'invalid'), { ...input, size: 26214401 }));
  await assertFails(setDoc(doc(admin, 'digitalBooks', 'early'), { ...input, status: 'published' }));
  await assertFails(getDoc(doc(guest, 'digitalBooks', 'one')));
  await assertFails(getDoc(doc(reader, 'digitalBooks', 'one')));
  await assertFails(getDocs(collection(reader, 'digitalBooks')));
  await assertSucceeds(getDocs(collection(admin, 'digitalBooks')));
  await assertFails(updateDoc(ref, { status: 'published', updatedAt: serverTimestamp() }));
  await assertSucceeds(updateDoc(ref, { status: 'draft', updatedAt: serverTimestamp() }));
  await assertFails(updateDoc(ref, { fileId: 'replacement', updatedAt: serverTimestamp() }));
  const published = { status: 'published', readerUrl: 'https://drive.google.com/file/d/file/view', updatedAt: serverTimestamp() };
  await assertFails(updateDoc(ref, published));
  await assertSucceeds(updateDoc(ref, { author: 'Fictional credit', updatedAt: serverTimestamp() }));
  await assertFails(updateDoc(ref, { ...published, readerUrl: 'https://evil.example/pdf' }));
  await assertFails(updateDoc(doc(inactive, 'digitalBooks', 'one'), published));
  await assertSucceeds(updateDoc(ref, published));
  await assertSucceeds(getDoc(doc(guest, 'digitalBooks', 'one')));
  const result = await assertSucceeds(getDocs(query(collection(guest, 'digitalBooks'), where('status', '==', 'published'))));
  assert.equal(result.size, 1);
  await assertFails(updateDoc(ref, { status: 'draft', readerUrl: '', updatedAt: serverTimestamp() }));
});
