const { test, after } = require('node:test');
const assert = require('node:assert/strict');
const { randomUUID } = require('node:crypto');
const { initializeApp, deleteApp } = require('firebase-admin/app');
const { getFirestore, FieldValue } = require('firebase-admin/firestore');
const { FirestoreRightsRepository, CreditLicenseService, TopupRequestService } = require('../protected');
if (!/^127\.0\.0\.1:\d+$/.test(process.env.FIRESTORE_EMULATOR_HOST || '')) throw Error('Local emulator required');
const app = initializeApp({ projectId: 'demo-bw-topup-tests' }, 'topup-tests'), db = getFirestore(app), repository = new FirestoreRightsRepository(db), clock = () => FieldValue.serverTimestamp(), ledger = new CreditLicenseService(repository, clock),
  service = new TopupRequestService({ repository, ledger, clock, methods: [{ id: 'bkash', label: 'bKash test', enabled: true, recipient: 'fictional test destination' }, { id: 'dutch-bangla', label: 'Bank test', enabled: true, recipient: 'fictional bank' }, { id: 'unconfigured', enabled: false }, { id: 'usdt', label: 'USDT', enabled: true, recipient: 'fictional wallet', currency: 'USDT', network: 'BEP-20', bdtPerUsdtMinor: 13000, minimumAmountMinor: 10001 }] });
after(() => deleteApp(app));
test('top-up request/reference do not credit wallets; verified approval is atomic and payment references cannot be reused', async () => {
  const uid = 'reader-' + randomUUID(), admin = 'admin-' + randomUUID();
  const paymentReference = 'REF' + randomUUID().replaceAll('-', '').toUpperCase();
  await db.doc('adminGrants/' + admin).set({ status: 'active', role: 'superuser' });
  const payload = { credits: 992, methodId: 'bkash', operationId: randomUUID(), reference: paymentReference };
  await assert.rejects(service.create(uid, { ...payload, reference: '' }), /payment-reference-required/);
  const first = await service.create(uid, payload);
  assert.deepEqual(await service.create(uid, payload), first);
  await assert.rejects(service.create(uid, { ...payload, credits: 993 }), /operation-mismatch/);
  await assert.rejects(service.create(uid, { ...payload, methodId: 'unconfigured' }), /payment-method-unavailable/);
  assert.equal((await db.doc('protectedWallets/' + uid).get()).exists, false);
  await assert.rejects(service.submitReference('other-reader', first.id, 'TESTREF123'), /request-not-found/);
  await service.submitReference(uid, first.id, paymentReference.toLowerCase());
  assert.equal((await db.doc('protectedWallets/' + uid).get()).exists, false);
  const approval = { decision: 'approve', confirmed: true, verifiedReference: paymentReference, verifiedAmountMinor: 99200 };
  await assert.rejects(service.review(uid, first.id, approval), /admin-required/);
  await assert.rejects(service.review(admin, first.id, { ...approval, confirmed: false }), /payment-verification-required/);
  await assert.rejects(service.review(admin, first.id, { ...approval, verifiedAmountMinor: 1 }), /payment-verification-required/);
  await Promise.all([service.review(admin, first.id, approval), service.review(admin, first.id, approval)]);
  assert.equal((await db.doc('protectedWallets/' + uid).get()).data().balance, 992);
  const other = await service.create('reader-' + randomUUID(), { ...payload, operationId: randomUUID() });
  await service.submitReference((await db.doc('protectedTopupRequests/' + other.id).get()).data().uid, other.id, paymentReference);
  await assert.rejects(service.review(admin, other.id, approval), /payment-reference-already-used/);
  const rejected = await service.create(uid, { ...payload, operationId: randomUUID() });
  await service.review(admin, rejected.id, { decision: 'reject', reason: 'Payment not received' });
  await assert.rejects(service.review(admin, rejected.id, approval), /request-not-pending/);
  assert.equal((await db.doc('protectedWallets/' + uid).get()).data().balance, 992);
  const list = await service.list(uid);
  assert.equal(list.length, 2); assert.ok(list.every(r => r.uid === uid));
});
test('USDT requests freeze the 130-taka quote, enforce minimum, and credit exact units after verification', async () => {
  const uid = 'reader-' + randomUUID(), admin = 'admin-' + randomUUID();
  await db.doc('adminGrants/' + admin).set({ status: 'active', role: 'superuser' });
  const hash = '0x' + randomUUID().replaceAll('-', '') + randomUUID().replaceAll('-', '');
  await assert.rejects(service.create(uid, { credits: 1, methodId: 'usdt', operationId: randomUUID(), reference: hash }), /payment-method-minimum/);
  const order = await service.create(uid, { credits: 1040, methodId: 'usdt', operationId: randomUUID(), reference: hash });
  const data = (await db.doc('protectedTopupRequests/' + order.id).get()).data();
  assert.equal(data.currency, 'USDT'); assert.equal(data.amountMinor, 8000000); assert.equal(data.bdtPerUsdtMinor, 13000);
  await assert.rejects(service.submitReference(uid, order.id, 'INVALID-HASH'), /invalid-payment-reference/);
  await service.submitReference(uid, order.id, hash);
  await assert.rejects(service.review(admin, order.id, { decision:'approve', confirmed:true, verifiedReference:hash, verifiedAmountMinor:800 }), /payment-verification-required/);
  await service.review(admin, order.id, { decision:'approve', confirmed:true, verifiedReference:hash, verifiedAmountMinor:8000000 });
  assert.equal((await db.doc('protectedWallets/' + uid).get()).data().balance, 1040);
});
test('bank requests require sender account and approval requires a unique verified statement reference', async () => {
  const uid = 'reader-' + randomUUID(), admin = 'admin-' + randomUUID();
  await db.doc('adminGrants/' + admin).set({ status:'active',role:'superuser' });
  const payload = { credits:1040, methodId:'dutch-bangla', operationId:randomUUID() };
  await assert.rejects(service.create(uid,payload), /sender-account-required/);
  const order = await service.create(uid,{...payload,senderAccountNumber:'TEST-ACCOUNT-123'});
  const data = (await db.doc('protectedTopupRequests/'+order.id).get()).data();
  assert.equal(data.status,'pending-review'); assert.equal(data.senderAccountNumber,'TEST-ACCOUNT-123');
  await assert.rejects(service.review(admin,order.id,{decision:'approve',confirmed:true,verifiedAmountMinor:104000}),/payment-verification-required/);
  await service.review(admin,order.id,{decision:'approve',confirmed:true,verifiedAmountMinor:104000,verifiedReference:'BANK-'+randomUUID()});
  assert.equal((await db.doc('protectedWallets/'+uid).get()).data().balance,1040);
  const { ReportingService } = require('../protected');
  const report = await new ReportingService(repository).report();
  assert.ok(report.totals.creditsSold >= 1040);
  assert.equal(report.totals.purchases, 0);
  assert.ok(report.entries.some(entry => entry.requestId === order.id && entry.kind === 'manually-verified-credit-topup' && entry.amount === 1040 && entry.amountMinor === 104000));
});
